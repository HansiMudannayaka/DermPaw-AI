# 23. CREATE SIX CROPS







# ============================================================















def create_crops(







    pil_img,







    crop_ratio=0.80







):















    image = pil_img.convert(







        "RGB"







    )























    width, height = image.size























    crop_width = max(















        1,















        int(







            width







            * crop_ratio







        )







    )























    crop_height = max(















        1,















        int(







            height







            * crop_ratio







        )







    )























    crops = [















        (







            "full",







            image.copy()







        )







    ]























    # ========================================================







    # CENTER







    # ========================================================















    center_left = max(















        0,















        (







            width







            - crop_width







        ) // 2







    )























    center_top = max(















        0,















        (







            height







            - crop_height







        ) // 2







    )























    crops.append(















        (







            "center",















            image.crop(







                (







                    center_left,















                    center_top,















                    center_left







                    + crop_width,















                    center_top







                    + crop_height







                )







            )







        )







    )























    # ========================================================







    # TOP LEFT







    # ========================================================















    crops.append(















        (







            "top_left",















            image.crop(







                (







                    0,















                    0,















                    crop_width,















                    crop_height







                )







            )







        )







    )























    # ========================================================







    # TOP RIGHT







    # ========================================================















    crops.append(















        (







            "top_right",















            image.crop(







                (







                    width







                    - crop_width,















                    0,















                    width,















                    crop_height







                )







            )







        )







    )























    # ========================================================







    # BOTTOM LEFT







    # ========================================================















    crops.append(















        (







            "bottom_left",















            image.crop(







                (







                    0,















                    height







                    - crop_height,















                    crop_width,















                    height







                )







            )







        )







    )























    # ========================================================







    # BOTTOM RIGHT







    # ========================================================















    crops.append(















        (







            "bottom_right",















            image.crop(







                (







                    width







                    - crop_width,















                    height







                    - crop_height,















                    width,















                    height







                )







            )







        )







    )























    return crops























