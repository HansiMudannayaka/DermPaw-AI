# 16. LAPLACIAN VARIANCE







# ============================================================















def laplacian_variance(







    gray_array







):















    gray_array = gray_array.astype(







        np.float32







    )























    center = (















        -4.0







        * gray_array[







            1:-1,







            1:-1







        ]







    )























    up = gray_array[







        :-2,







        1:-1







    ]























    down = gray_array[







        2:,







        1:-1







    ]























    left = gray_array[







        1:-1,







        :-2







    ]























    right = gray_array[







        1:-1,







        2:







    ]























    laplacian = (















        center







        + up







        + down







        + left







        + right







    )























    return float(







        np.var(







            laplacian







        )







    )























