# 20. NORMALIZED ENTROPY







# ============================================================















def calculate_normalized_entropy(







    probabilities







):















    probabilities = np.asarray(















        probabilities,















        dtype=np.float32







    )























    safe_probabilities = np.clip(















        probabilities,















        1e-8,















        1.0







    )























    entropy = -np.sum(















        safe_probabilities















        * np.log(







            safe_probabilities







        )







    )























    normalized_entropy = float(















        entropy















        /















        np.log(







            NUM_CLASSES







        )







    )























    return normalized_entropy























