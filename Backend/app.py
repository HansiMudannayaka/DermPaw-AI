# 21. MAHALANOBIS OOD







# ============================================================















def calculate_ood_score(







    preprocessed_image







):















    batch = np.expand_dims(















        preprocessed_image,















        axis=0







    )























    embedding = embedding_model.predict(















        batch,















        verbose=0















    )[0]























    # Use float64 here to match the Kaggle old-style OOD







    # calibration (np.cov + np.linalg.pinv) as closely as possible.







    embedding = np.asarray(















        embedding,















        dtype=np.float64















    ).reshape(-1)























    diff = (















        embedding















        - MEAN_EMBEDDING







    )























    squared_distance = float(















        np.einsum(















            "i,ij,j->",















            diff,















            INV_COV,















            diff







        )







    )























    squared_distance = max(















        squared_distance,















        0.0







    )























    distance = float(















        math.sqrt(







            squared_distance







        )







    )























    is_ood = bool(















        distance







        > OOD_THRESHOLD







    )























    return {















        "score":







            distance,















        "threshold":







            OOD_THRESHOLD,















        "isOOD":







            is_ood







    }























